const {webkit,chromium}=require('playwright');
const assert=require('node:assert/strict');
const url='https://evelynyyyyy.github.io/study-abroad/topik-vocab/';
async function type(page,py){for(const k of py)await page.locator('.pinyin-keyboard [data-pinyin-key="'+k+'"]').click()}
(async()=>{for(const [name,engine] of [['webkit',webkit],['chromium',chromium]]){
 const browser=await engine.launch();const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url,{waitUntil:'load'});
 await page.evaluate(()=>{
   view='smart';smartTask={word:[1,'가','成为'],type:'typing',mode:'meaning'};
   state.inputMethod='virtual';didCheck=false;pendingRating=false;typed='';pinyinComposition='';render();
 });
 assert.equal(await page.evaluate(()=>window.CHINESE_IME_ENGINE),'simple-ime');
 assert.equal(await page.locator('.pinyin-keyboard').count(),1);
 await type(page,'chengwei');
 assert.equal(await page.locator('#pinyin-composition').textContent(),'chengwei');
 assert.ok((await page.locator('#pinyin-candidates').textContent()).includes('成为'));
 await page.locator('[data-pinyin-choice="0"]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为');
 assert.equal(await page.locator('#pinyin-composition').textContent(),'');
 await page.locator('[data-pinyin-mode="numbers"]').click();
 await page.locator('[data-pinyin-symbol="'+encodeURIComponent('（')+'"]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（');
 await page.locator('[data-pinyin-mode="letters"]').click();
 await type(page,'shijian');
 assert.ok((await page.locator('#pinyin-candidates').textContent()).includes('时间'));
 await page.locator('[data-pinyin-choice="0"]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间');
 await page.locator('[data-pinyin-mode="numbers"]').click();
 await page.locator('[data-pinyin-symbol="'+encodeURIComponent('）')+'"]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间）');
 await page.locator('[data-pinyin-key="backspace"]').last().click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间');
 await page.locator('[data-pinyin-mode="letters"]').click();
 await type(page,'jian');
 assert.equal(await page.locator('#pinyin-composition').textContent(),'jian');
 await page.locator('[data-pinyin-key="backspace"]').first().click();
 assert.equal(await page.locator('#pinyin-composition').textContent(),'jia');
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间');
 await page.locator('[data-pinyin-key="n"]').click();
 await page.locator('[data-pinyin-choice="1"]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间间');
 await type(page,'chengwei');
 await page.locator('.pinyin-keyboard [data-smart-submit]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间间成为');
 assert.equal(await page.locator('#pinyin-composition').textContent(),'');
 await page.locator('.pinyin-keyboard [data-smart-submit]').click();
 assert.equal(await page.locator('#spell-input').inputValue(),'成为（时间间成为');
 assert.equal(await page.locator('.smart-submit').count(),1);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({browser:name,kind:'production-study-page',engine:'simple-ime',answer:await page.locator('#spell-input').inputValue(),candidateChecks:['成为','时间','间'],punctuation:true,compositionBackspace:true,returnDoesNotSubmit:true,errors}));
 await browser.close();
}})().catch(e=>{console.error(e);process.exit(1)});
