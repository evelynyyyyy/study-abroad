'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const app=fs.readFileSync('topik-vocab/app.js','utf8');
const scheduler=fs.readFileSync('topik-vocab/smart-scheduler.js','utf8');
const c={window:{},Date,Math};vm.runInNewContext(scheduler,c);
const S=c.window.TOPIK_SMART;
assert.match(app,/smartRecord\(correct\?'good':'again'\)/,'typed answer must be graded automatically');
assert.match(app,/smartRecord\('again'\)/,'unknown button maps to Again');
assert.match(app,/TOPIK_SMART\.review\(state,word\[1\],mode,correct,Date\.now\(\),result\)/,'review must update scheduler');
assert.match(app,/TOPIK_SMART\.learningResult\(state,word\[1\],mode,correct,Date\.now\(\)\)/,'learning never invokes review grading');
for(const forbidden of ['data-smart-rate','data-unfamiliar','function smartRate(','function markUnfamiliar(','请选择刚才回忆的真实感受'])assert.ok(!app.includes(forbidden),'subjective button removed: '+forbidden);
assert.match(app,/didCheck\?'<div class="smart-actions"><button class="primary smart-action" data-smart-next="1">继续 →<\/button><\/div>'/);
const now=Date.now(),state={progress:{},lifecycle:{词:{wordState:'LEARNING',learningProof:{round:0,lastSerial:0,directions:[]}}},learningActiveWindow:4};
S.learningResult(state,'词','meaning',true,now);
assert.equal(state.lifecycle.词.wordState,'LEARNING');
assert.equal(state.progress.词,undefined,'new-word success must not invoke FSRS');
S.learningResult(state,'词','spell',false,now+1000);
assert.equal(state.lifecycle.词.learningProof.round,0,'wrong answer resets streak');
assert.equal(state.lifecycle.词.graduatedAt,undefined,'wrong answer never graduates');
const reviewState={progress:{},lifecycle:{词:{wordState:'REVIEW',graduatedAt:now}}};
const good=S.review(reviewState,'词','meaning',true,now,'good');
assert.equal(good.lastResult,'good');
assert.ok(good.nextReview>now);
const before=good.stability;
const again=S.review(reviewState,'词','meaning',false,now+1000,'again');
assert.equal(again.lastResult,'again');
assert.equal(again.phase,'relearning');
assert.ok(again.stability<before,'Again reduces stability');
assert.equal(reviewState.lifecycle.词.graduatedAt,now,'review failure preserves graduation');
assert.equal(reviewState.progress.词.spell,undefined,'FSRS direction independence');
const recovered=S.review(reviewState,'词','meaning',true,again.nextReview+1,'good');
assert.equal(recovered.phase,'relearning','correct answer still updates relearning schedule');
assert.ok(recovered.nextReview>again.nextReview);
console.log('Automatic Good/Again mapping, no manual ratings, graduation reset, FSRS review/relearning verified');
