const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const app=fs.readFileSync('topik-vocab/app.js','utf8'),css=fs.readFileSync('topik-vocab/styles.css','utf8');
assert.match(css,/\.smart-start-stack\s*\{[^}]*gap:16px/);
assert.match(css,/\.smart-start-stack>\.smart-start\s*\{[^}]*width:100%/);
assert.match(app,/class="smart-start-stack"/);
assert.match(app,/smartPool==='learn'\?stats\.graduated/);
assert.match(app,/smartPool==='review'&&\(phase==='REVIEW'\|\|phase==='RELEARNING'\)/);
assert.match(app,/smartReviewCompleted/);
assert.match(app,/smartReviewGoal/);
assert.match(app,/smartSessionTasks\[smartPool\]=0/);
assert.match(app,/const STORAGE='topik_lab_v2'/);
const source=app.slice(app.indexOf('function smartDailyStats(){'),app.indexOf('function home(){'));
const now=new Date(),today=now.toLocaleDateString('sv-SE');
const state={daily:{[today]:{learned:['新','新'],smartReviewCompleted:['复','复'],smartReviewGoal:4,smartReviewTasks:3,smartLearnTasks:2}},dailyGoal:100,lifecycle:{'新':{seenAt:Date.now()},'学':{wordState:'LEARNING'},'复':{wordState:'REVIEW'},'毕':{wordState:'REVIEW',graduatedAt:Date.now()}}};
const context={state,today:()=>today,dayInfo:()=>state.daily[today],scope:()=>[['','新'],['','学'],['','复'],['','毕']],TOPIK_SMART:{wordState:(s,k)=>s.lifecycle[k]?.wordState||'NEW',due:(s,k)=>k==='复'},Date,Set,Number,Math};
vm.createContext(context);vm.runInContext(source+';this.stats=smartDailyStats;',context);
let s=context.stats();
assert.equal(s.introduced,1);assert.equal(s.graduated,1);assert.equal(s.learning,1);
assert.equal(s.reviewDone,1);assert.equal(s.reviewGoal,4);assert.equal(s.reviewDue,1);
assert.equal(s.reviewTasks,3);assert.equal(s.learnTasks,2);
state.daily[today].smartReviewCompleted.push('复');assert.equal(context.stats().reviewDone,1);
state.daily[today].smartReviewGoal=0;assert.equal(context.stats().reviewGoal,2);
state.daily[today].smartReviewGoal=4;
const old={...state.daily[today]};delete old.smartReviewCompleted;delete old.smartReviewGoal;state.daily[today]=old;
assert.equal(context.stats().reviewDone,0,'legacy data does not invent review completions');
state.daily[today]={learned:[]};assert.equal(context.stats().introduced,0,'refresh uses persisted state');
const yesterday=new Date(Date.now()-86400000).toLocaleDateString('sv-SE');state.lifecycle['毕'].graduatedAt=Date.now()-86400000;
assert.equal(context.stats().graduated,yesterday===today?1:0,'graduation must use local calendar date');
console.log('Smart progress and layout invariants passed');
