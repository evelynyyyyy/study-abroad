'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c={window:{},Date};vm.runInNewContext(fs.readFileSync('topik-vocab/lexicon-quality.js','utf8'),c);
const L=c.window.TOPIK_LEXICON;
assert.notEqual(L.entries['눈'][0].id,L.entries['눈'][1].id,'distinct senses have stable IDs');
assert.equal(L.entries['눈'][0].review,'needs-human-review','no fake human approval');
assert.equal(L.metadata('먹다','吃').review,'needs-human-review');
assert.equal(L.acceptedSpell('집',[1,'집','家'],[[1,'집','家'],[1,'댁','家']]),true,'identical Chinese meanings accept alternative spelling');
assert.equal(L.acceptedSpell('학교',[1,'집','家'],[[1,'집','家'],[1,'학교','学校']]),false);
assert.equal(L.acceptedSpell('밤',[1,'눈','雪'],[[1,'눈','雪'],[1,'밤','夜晚']]),false);
assert.equal(L.reverse['먹었어요'][0].lemma,'먹다');
assert.equal(L.reverse['걸어요'][0].irregular,true);
assert.equal(L.similar('사람','사랑'),true);
assert.equal(L.similar('사람','학교'),false);
const state={};assert.equal(L.confusion(state,'사람','사랑',[[1,'사람','人'],[1,'사랑','爱']],'spell'),true);
assert.equal(state.confusions['사람⇄사랑'].count,1);
assert.equal(L.confusion(state,'사람','학교',[[1,'사람','人'],[1,'사랑','爱']],'spell'),false);
const app=fs.readFileSync('topik-vocab/app.js','utf8'),html=fs.readFileSync('topik-vocab/index.html','utf8');
assert.ok(app.includes('TOPIK_LEXICON.acceptedSpell'));
assert.ok(app.includes('TOPIK_LEXICON.confusion'));
assert.ok(html.includes('lexicon-quality.js?v=2.1.1'));
console.log('Sense IDs, unverified statuses, inflection, alternative answers and confusion regression passed.');
