'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c={window:{}};vm.runInNewContext(fs.readFileSync('topik-vocab/reset-progress.js','utf8'),c);
const R=c.window.TOPIK_RESET;
const words=[[1,'집','家'],[1,'공부','学习'],[2,'공부','学习'],[2,'학교','学校']];
const make=()=>({progress:{집:{spell:{wrong:2}},공부:{meaning:{correct:3}},학교:{spell:{correct:5}}},lifecycle:{집:{stage:'shown'},공부:{stage:'mastered'},학교:{stage:'learning'}},relearn:{집:{directions:{}},학교:{directions:{}}},daily:{'2026-11-19':{learned:['집','공부','학교'],spell:8}},smartHistory:['집','공부','학교'],smartAnswerHistory:[{ko:'집',result:'again'},{ko:'공부',result:'correct'},{ko:'학교',result:'correct'}],theme:'dark',dailyGoal:20,level:1,extra:[[1,'새','新']],favorites:['집']});
let s=make(),out=R.reset(s,words,1);
assert.equal(out.removed,1);assert.equal(out.shared,1);
assert.equal(s.progress.집,undefined);assert.equal(s.lifecycle.집,undefined);assert.equal(s.relearn.집,undefined);
assert.equal(s.progress.공부.meaning.correct,3);assert.equal(s.progress.학교.spell.correct,5);
assert.deepEqual(Array.from(s.daily['2026-11-19'].learned),['공부','학교']);
assert.deepEqual(Array.from(s.smartHistory),['공부','학교']);
assert.equal(s.smartAnswerHistory.length,2);
assert.equal(s.legacyMigrated,true);
assert.equal(JSON.parse(JSON.stringify(s)).progress.집,undefined,'reset survives reload');
assert.equal(s.theme,'dark');assert.equal(s.dailyGoal,20);assert.equal(s.extra.length,1);
s=make();out=R.reset(s,words,'all');
assert.equal(out.removed,3);assert.equal(Object.keys(s.progress).length,0);
assert.equal(Object.keys(s.lifecycle).length,0);assert.equal(Object.keys(s.relearn).length,0);
assert.equal(Object.keys(s.daily).length,0);assert.equal(s.smartHistory.length,0);assert.equal(s.smartAnswerHistory.length,0);
assert.equal(s.theme,'dark');assert.equal(s.extra[0][1],'새');assert.equal(s.favorites[0],'집');
const backup={version:2,state:make()};assert.equal(R.validateBackup(backup),true);
assert.throws(()=>R.validateBackup({version:2,state:{progress:[],extra:[]}}));
assert.throws(()=>R.validateBackup({version:2,state:{progress:{},extra:'bad'}}));
const app=fs.readFileSync('topik-vocab/app.js','utf8'),html=fs.readFileSync('topik-vocab/index.html','utf8');
for(const marker of ['学习数据管理','data-reset-scope','TOPIK_RESET.reset','TOPIK_RESET.validateBackup','legacyMigrated','levelDayInfo'])assert.ok(app.includes(marker),marker);
assert.ok(html.includes('./reset-progress.js?v=2.0.4'));
console.log('Scoped/full reset, shared-word preservation, backup validation and reload tests passed.');
