const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{},Date,Math};vm.runInNewContext(fs.readFileSync('topik-vocab/first-learning.js','utf8'),context);vm.runInNewContext(fs.readFileSync('topik-vocab/smart-scheduler.js','utf8'),context);
const S=context.window.TOPIK_SMART,F=context.window.TOPIK_FIRST_LEARNING;
const state={progress:{},lifecycle:{}},words=[[1,'집','家'],[1,'학교','学校'],[1,'물','水']];
const day={learned:[]};let now=Date.now();
assert.equal(S.select(state,words,day,2,[],now).type,'show');
F.shown(state,'집');day.learned.push('집');
assert.equal(S.stage(state,'집'),'shown');
assert.equal(state.progress['집'],undefined,'first reveal is not graded');
assert.notEqual(S.select(state,words,day,2,['집'],now)?.word[1],'집','no immediate recall');
F.shown(state,'학교');day.learned.push('학교');
assert.equal(S.select(state,words,day,2,['집','학교'],now),null,'daily target limits new introductions');
let m=S.review(state,'집','spell',false,now);
assert.equal(m.incorrect,1);assert.ok(m.nextReview>now);assert.ok(m.interval<.1);
F.recall(state,'집','spell');
assert.equal(S.stage(state,'집'),'learning');
assert.equal(state.progress['집'].meaning,undefined,'directions remain independent');
S.review(state,'집','meaning',true,now+16000);F.recall(state,'집','meaning');
assert.equal(S.stage(state,'집'),'reviewing');
const prev=state.progress['집'].spell.memory.stability;
S.review(state,'집','spell',true,now+S.DAY);
assert.ok(state.progress['집'].spell.memory.stability>prev);
const due=S.select(state,words,day,2,['학교','물'],now+S.DAY*2);
assert.equal(due.type,'typing');
// Check that the primary button invokes the new engine and release marker is present.
const app=fs.readFileSync('topik-vocab/app.js','utf8');
const html=fs.readFileSync('topik-vocab/index.html','utf8');
assert.ok(app.includes('data-smart-start="1"'));
assert.ok(app.includes('function startSmart(){'));
assert.ok(app.includes("view==='smart'?smartScreen()"));
assert.ok(app.includes('TOPIK_SMART.select('));
assert.ok(html.includes('smart-scheduler.js?v=2.0.1'));
assert.ok(app.includes('版本 v2.0.2'));
const homeSource=app.slice(app.indexOf('function home(){'),app.indexOf('function recordsHome(){'));
assert.ok(!homeSource.includes('每轮最多 10 词'));
assert.ok(!homeSource.includes('data-start="learn"'));

const unknownState={progress:{},lifecycle:{}};
const unknownDay={learned:['집','학교','물']};
for(const w of words)F.shown(unknownState,w[1]);
const before=S.normalize(unknownState,'집','spell',now);
const again=S.review(unknownState,'집','spell',false,now,'again');
assert.equal(again.lastResult,'again','explicit unknown is distinct from typed wrong');
assert.equal(again.incorrect,1,'unknown counts as a failed recall');
assert.equal(again.correct,0,'unknown never counts as correct typing');
assert.ok(again.stability<before.stability,'unknown reduces stability');
assert.equal(unknownState.progress['집'].meaning,undefined,'other direction untouched');
assert.equal(S.due(unknownState,'집','spell',now+30_000),false,'not repeated immediately');
assert.equal(S.due(unknownState,'집','spell',now+61_000),true,'retry becomes due in one minute');
assert.notEqual(S.select(unknownState,words,unknownDay,3,['집'],now+30_000)?.word[1],'집','intervening card is selected');
const retry=S.select(unknownState,[words[0]],unknownDay,3,['학교','물'],now+61_000);
assert.equal(retry?.word[1],'집','unknown direction becomes available for later retry');
assert.equal(retry?.mode,'spell','retry preserves direction');
const twice=S.review(unknownState,'집','spell',false,now+61_000,'wrong');
assert.equal(twice.lastResult,'wrong','typed wrong is a separate result');
assert.equal(twice.incorrect,2);
assert.equal(unknownState.progress['집'].meaning,undefined);
assert.ok(app.includes('data-smart-unknown="1"'),'unknown button is visible');
assert.ok(app.includes('function smartDontKnow()'),'unknown handler exists');
assert.ok(app.includes("smartRecord('again')"),'unknown invokes Again');
assert.ok(app.includes('didCheck=true;persist();render()'),'feedback persists before continuing');
assert.ok(app.includes('data-smart-next="1">继续 →'),'feedback requires explicit continue');
console.log('Continuous scheduler, unknown -> answer -> Again -> later retry, and UI tests passed');
