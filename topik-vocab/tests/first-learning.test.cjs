const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{},Date,Math};
vm.runInNewContext(fs.readFileSync('topik-vocab/first-learning.js','utf8'),context);
const engine=context.window.TOPIK_FIRST_LEARNING;
const state={progress:{},lifecycle:{}};
const ko='사과';
assert.equal(engine.stage(state,ko),'unseen');
assert.equal(engine.shown(state,ko),true);
assert.equal(engine.stage(state,ko),'shown');
assert.equal(state.progress[ko],undefined,'showing a word must not grade it');
assert.equal(engine.shown(state,ko),false,'a word can only be first-shown once');
engine.recall(state,ko,'meaning');
assert.equal(engine.stage(state,ko),'learning');
assert.equal(state.lifecycle[ko].first.spell,false);
engine.recall(state,ko,'spell');
assert.equal(engine.stage(state,ko),'reviewing');
state.progress[ko]={meaning:{step:4},spell:{step:3}};
engine.mastery(state,ko);
assert.equal(engine.stage(state,ko),'reviewing','one mastered direction is insufficient');
state.progress[ko].spell.step=4;
engine.mastery(state,ko);
assert.equal(engine.stage(state,ko),'mastered');
state.progress[ko].spell.step=0;
engine.mastery(state,ko);
assert.equal(engine.stage(state,ko),'reviewing','mastery can be lost');
const words=[['1','사과','苹果'],['1','물','水'],['1','책','书'],['1','집','家'],['1','밥','饭']];
const batch=engine.newBatch(words);
assert.equal(batch.phase,'show');
assert.equal(batch.words.length,5);
for(let i=0;i<5;i++)engine.reveal(batch);
assert.equal(batch.phase,'intro');
assert.equal(batch.queue.length,10,'two directions per word');
for(const w of words){
 assert.equal(batch.queue.filter(q=>q.word[1]===w[1]).length,2);
 assert.equal(batch.queue.filter(q=>q.word[1]===w[1]&&q.mode==='meaning').length,1);
 assert.equal(batch.queue.filter(q=>q.word[1]===w[1]&&q.mode==='spell').length,1);
}
for(let i=1;i<batch.queue.length;i++)assert.notEqual(batch.queue[i].word[1],batch.queue[i-1].word[1],'avoid adjacent duplicate words');
engine.next(batch);assert.equal(batch.phase,'typing');
engine.result(batch,false);assert.equal(batch.retry.length,1);
engine.result(batch,false);assert.equal(batch.retry.length,2);
engine.result(batch,false);assert.equal(batch.retry.length,2,'bounded retries');
console.log('First-learning lifecycle and typing test passed.');
