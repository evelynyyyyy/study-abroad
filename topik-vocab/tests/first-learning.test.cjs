const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c={window:{},Date,Math};vm.runInNewContext(fs.readFileSync('topik-vocab/first-learning.js','utf8'),c);
vm.runInNewContext(fs.readFileSync('topik-vocab/smart-scheduler.js','utf8'),c);
const F=c.window.TOPIK_FIRST_LEARNING,S=c.window.TOPIK_SMART;
const state={progress:{},lifecycle:{}},ko='사과',now=Date.now();
assert.equal(F.stage(state,ko),'unseen');assert.equal(F.shown(state,ko),true);
assert.equal(F.stage(state,ko),'shown');assert.equal(state.progress[ko],undefined);
assert.equal(F.shown(state,ko),false);
S.review(state,ko,'meaning',true,now,'good');F.recall(state,ko,'meaning');
assert.equal(F.stage(state,ko),'learning');
S.review(state,ko,'spell',true,now,'easy');F.recall(state,ko,'spell');
assert.equal(F.stage(state,ko),'consolidating','one success per direction is not mastery');
assert.equal(S.mastered(state,ko),false);
state.progress[ko].meaning.step=7;state.progress[ko].spell.step=7;
F.mastery(state,ko);assert.notEqual(F.stage(state,ko),'mastered','old step counters are not proof');
const words=[['1','사과','苹果'],['1','물','水'],['1','책','书'],['1','집','家'],['1','밥','饭']];
const batch=F.newBatch(words);
for(let i=0;i<5;i++)F.reveal(batch);
assert.equal(batch.phase,'intro');assert.equal(batch.queue.length,10);
for(const w of words)assert.equal(batch.queue.filter(q=>q.word[1]===w[1]).length,2);
F.next(batch);F.result(batch,false);assert.equal(batch.retry.length,1);
console.log('Six-stage learning lifecycle and conservative mastery tests passed.');
